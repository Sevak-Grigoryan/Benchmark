#!/bin/bash
# Login-node driver: one benchmark episode from flight to published Simulation_N.
#   cd <this repository>
#   nohup bash jobs/make_episode.sh <forest easy v2 idx> "<test names or empty>" <Simulation_N> >> logs/make_episode_<idx>.log 2>&1 &
# 1. submits jobs/gpu_fly_and_render.sbatch (expert flight + render) and resubmits it after a bad GPU, until every unit is done;
# 2. publishes Benchmark/Easy/Forest/<Simulation_N> (publishing/publish_episode.py), scores the expert flight and runs the
#    evaluator self-test into its results/.
# Paths come from jobs/config.sh: raw flights and render slices go to $BENCH_RUNS/<episode>, episodes to $BENCH_DATA.
# Do not edit this file while a driver runs (bash reads scripts lazily).
set -u
IDX=${1:?Forest Easy v2 index}; TESTS=${2:-}; SIM=${3:-}
source "$(dirname "$(readlink -f "$0")")/config.sh"
DEST=$BENCH_DATA/Easy/Forest/$SIM
B=$BENCH_CODE
SCENE=easy_v2_$(printf %03d "$IDX"); EP=vlncol_forest_$(printf %03d "$IDX")
ROOT=$BENCH_RUNS
LOGS=$B/logs; EXCL=$EXCLUDE_NODES
NAME=VLNBench-Forest-$(printf %03d "$IDX")
log() { echo "$(date '+%F %T') $*"; }
mkdir -p "$ROOT" "$LOGS"

complete() {
  [ -f "$ROOT/$EP/flight/FLIGHT_DONE" ] || return 1
  for n in $TESTS; do [ -f "$ROOT/colltest_$n/flight/FLIGHT_DONE" ] || return 1; done
  if [ -f "$ROOT/$EP/flight/FLIGHT_OK" ]; then
    read F0 F1 < <(python3 $B/simulation/episode_frames.py "$ROOT/$EP/flight")
    for ((s = F0; s < F1; s += 900)); do [ -f "$ROOT/$EP/slices/slice_$(printf %06d $s).mp4" ] || return 1; done
  fi
  return 0
}

tries=0
while ! complete && [ $tries -lt 6 ]; do
  tries=$((tries + 1))
  j=$(sbatch --parsable --export=ALL -p $SLURM_PARTITION --exclude=$EXCL -J $NAME -o "$LOGS/%x_%j.out" -e "$LOGS/%x_%j.err" \
      $B/jobs/gpu_fly_and_render.sbatch "$SCENE" "$EP" "$ROOT" "$TESTS")
  log "submit job $j (try $tries, exclude $EXCL)"
  while squeue -j "$j" -h 2>/dev/null | grep -q .; do sleep 60; done
  sleep 5
  out="$LOGS/${NAME}_$j.out"
  if grep -q "^BAD GPU" "$out" 2>/dev/null; then
    node=$(grep -h "^BAD GPU" "$out" | head -1 | awk '{print $3}'); EXCL="$EXCL,$node"; log "bad GPU on $node -> resubmit"; continue
  fi
  log "job $j ended, exit $(sacct -j "$j" -X -n -o ExitCode | tr -d ' ')"
  grep -h "attempt\|episode window\|video\|job done" "$out" | sed 's/^/    /'
done
complete && log "ALL DONE $EP" || log "WARNING: not every unit finished after $tries jobs"

# publish into the benchmark, score the expert, checker self-test; publish refuses a non-empty destination
if [ -n "$SIM" ] && [ -f "$ROOT/$EP/flight/FLIGHT_OK" ] && [ ! -f "$DEST/task.json" ]; then
  python3 $B/publishing/publish_episode.py --work "$ROOT/$EP" --dest "$DEST" || log "PUBLISH FAILED"
fi
if [ -n "$SIM" ] && [ -f "$DEST/task.json" ]; then
  python3 $B/evaluation/evaluate.py "$DEST" --telemetry "$DEST/reference/telemetry.json" --actions "$DEST/reference/action.json" \
    -o "$DEST/results/reference_score.json" | grep -E '"success"|"episode_end"|"navigation_error_m"|"collided"'
  python3 $B/evaluation/evaluator_selftest.py "$DEST" -o "$DEST/results/checker_selftest.json" | grep -c PASS | sed 's/^/    self-test PASS cases: /'
fi
for n in $TESTS; do
  f="$ROOT/colltest_$n/flight/collision.json"
  [ -f "$f" ] && python3 -c "import json;c=json.load(open('$f'));p=c.get('first_prohibited');print('    colltest_$n', c['version'], 'prohibited:', p and (p['drone_part'], p['total_impulse_ns'], [q['separation'] for q in p['points']]))"
done
log "finished"
